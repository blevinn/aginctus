// Package pluginbuild generates static application composition. Generation never
// imports implementations, resolves modules or executes plugin code.
package pluginbuild

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"go/token"
	"io"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

const APIVersion = "aginctus.dev/plugin-build/v1alpha1"

// Manifest selects trusted Go factories, not runtime instances or permissions.
// Dependencies and versions belong to the ordinary pinned Go module graph.
type Manifest struct {
	APIVersion string      `json:"api_version"`
	Package    string      `json:"package"`
	Plugins    []Selection `json:"plugins"`
}

// Selection names an exported, parameterless factory returning plugin.Plugin (or
// an implementing concrete type). Factories must be deterministic and I/O-free;
// dependency resolution is the registry's job, not constructor/init side effects.
type Selection struct {
	ImportPath  string `json:"import_path"`
	Constructor string `json:"constructor"`
}

var importPath = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._~/-]*$`)

// Generate rejects unknown fields, extra documents, invalid source identifiers
// and duplicate selections. It returns formatted source independent of manifest
// enumeration order. Descriptor/dependency validation happens at composition,
// before runtime configuration or mutation, using the existing registry.
func Generate(raw []byte) ([]byte, error) {
	var manifest Manifest
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&manifest); err != nil {
		return nil, fmt.Errorf("decode build manifest: %w", err)
	}
	if err := decoder.Decode(new(any)); err != io.EOF {
		return nil, fmt.Errorf("build manifest must contain one JSON object")
	}
	if manifest.APIVersion != APIVersion {
		return nil, fmt.Errorf("unsupported build manifest API version")
	}
	if !token.IsIdentifier(manifest.Package) || manifest.Package == "_" {
		return nil, fmt.Errorf("invalid generated package name")
	}
	selections := slices.Clone(manifest.Plugins)
	slices.SortFunc(selections, func(a, b Selection) int {
		if c := strings.Compare(a.ImportPath, b.ImportPath); c != 0 {
			return c
		}
		return strings.Compare(a.Constructor, b.Constructor)
	})
	for i, selection := range selections {
		if !importPath.MatchString(selection.ImportPath) || strings.Contains(selection.ImportPath, "//") {
			return nil, fmt.Errorf("invalid selected import path")
		}
		for _, part := range strings.Split(selection.ImportPath, "/") {
			if part == "" || part == "." || part == ".." {
				return nil, fmt.Errorf("invalid selected import path component")
			}
		}
		if !token.IsIdentifier(selection.Constructor) || !token.IsExported(selection.Constructor) {
			return nil, fmt.Errorf("selected constructor must be an exported Go identifier")
		}
		if i > 0 && selection == selections[i-1] {
			return nil, fmt.Errorf("duplicate selected factory")
		}
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by aginctus-plugin-gen; DO NOT EDIT.\n\npackage %s\n\nimport (\n\"context\"\n\"github.com/blevinn/aginctus/internal/plugins\"\n", manifest.Package)
	for i, selection := range selections {
		fmt.Fprintf(&out, "selected%d %s\n", i, strconv.Quote(selection.ImportPath))
	}
	fmt.Fprintln(&out, ")\n\n// New composes only compiled factories. It creates no runtime instances or grants.\nfunc New(ctx context.Context) (*plugins.Registry, error) {\nif err := ctx.Err(); err != nil { return nil, err }\nreturn plugins.New(ctx,")
	for i, selection := range selections {
		fmt.Fprintf(&out, "selected%d.%s(),\n", i, selection.Constructor)
	}
	fmt.Fprintln(&out, ")\n}")
	return format.Source(out.Bytes())
}
